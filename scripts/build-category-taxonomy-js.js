const fs = require("fs");
const path = require("path");

const src = path.join(__dirname, "..", "data", "category-taxonomy.proposal.json");
const o = JSON.parse(fs.readFileSync(src, "utf8"));

const parents = o.parents.map((p) => {
  const children = [];
  const seen = new Set();
  for (const c of p.children) {
    const title = c.title === "(Chưa gắn leaf)" ? "Khác" : c.title;
    // Gộp “Khác” vào “Tài Khoản Khác” — không tạo mục sidebar trùng
    if (/^khác$/i.test(title)) continue;
    const slug = c.slug;
    const key = title.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    children.push({ title, slug: title === "Khác" ? "khac" : slug });
  }
  return {
    slug: p.slug,
    title: p.title,
    seoTitle: p.seoTitle || `${p.title} giá rẻ | Vua MMO`,
    note: p.note || "",
    children
  };
});

const payload = { version: 2, parents };
const out = `/* Taxonomy cha → con (SEO). Generated by scripts/build-category-taxonomy-js.js */
const CATEGORY_TAXONOMY = ${JSON.stringify(payload, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, "..", "js", "category-taxonomy.js"), out);
console.log(
  "Wrote js/category-taxonomy.js",
  parents.map((p) => `${p.slug}:${p.children.length}`).join(", ")
);
